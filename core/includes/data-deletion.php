const PAGE_SLUG = 'astrea-core-data-deletion';

const DELETE_ACTION = 'astrea_delete_all_core_data';
const DELETE_NONCE  = 'astrea_delete_all_core_data_nonce';

/** The exact phrase a user must type to confirm — never accepted case-insensitively or partially. */
const CONFIRM_PHRASE = '削除する';

