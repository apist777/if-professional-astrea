add_action( 'admin_post_' . DELETE_ACTION, __NAMESPACE__ . '\\handle_delete' );

/**
 * Handles the confirmed deletion request. Refuses (redisplays the form
 * with an error, deletes nothing) unless every guard passes: capability,
 * Nonce, the checkbox, and an exact match of the typed phrase.
 *
 * @return void
 */
function handle_delete() {
	if ( ! current_user_can( 'manage_options' ) ) {
		wp_die( esc_html__( 'この操作を行う権限がありません。', 'astrea-core' ) );
	}

	check_admin_referer( DELETE_ACTION, DELETE_NONCE );

	$understood = isset( $_POST['confirm_understood'] ) && '1' === $_POST['confirm_understood'];
	$phrase     = isset( $_POST['confirm_phrase'] ) ? sanitize_text_field( wp_unslash( (string) $_POST['confirm_phrase'] ) ) : '';

	if ( ! $understood || CONFIRM_PHRASE !== $phrase ) {
		add_settings_error(
			'astrea_core_data_deletion',
			'astrea_data_deletion_not_confirmed',
			__( '確認内容が一致しないため、削除は行われませんでした。', 'astrea-core' )
		);
		set_transient( 'settings_errors', get_settings_errors(), 30 );
		wp_safe_redirect( admin_url( 'admin.php?page=' . PAGE_SLUG . '&settings-updated=1' ) );
		exit;
	}

	$deleted = delete_all_core_data();

	set_transient(
		'settings_errors',
		array(
			array(
				'setting' => 'astrea_core_data_deletion',
				'code'    => 'astrea_data_deletion_complete',
				'message' => sprintf(
					/* translators: %d: number of deleted posts across all Core post types */
					__( 'ASTREA Coreのデータを削除しました（投稿 %d件、設定・一時データを含む）。', 'astrea-core' ),
					$deleted['posts']
				),
				'type'    => 'success',
			),
		),
		30
	);
	wp_safe_redirect( admin_url( 'admin.php?page=' . PAGE_SLUG . '&settings-updated=1' ) );
	exit;
}

/**
 * Deletes every piece of Core-owned data. Idempotent and safe to run more
 * than once: each step queries for what currently exists rather than
 * acting on a fixed pre-computed list, so a second run (or a run that
 * picks up after an earlier one was interrupted, e.g. by a PHP timeout on
 * a very large Contact table) simply finds nothing left and does nothing
 * — there is no WordPress DB transaction to roll back, so resumability
 * stands in for a transaction guarantee.
 *
 * @return array{posts: int, options: int} Counts, for the confirmation message.
 */
function delete_all_core_data(): array {
	$posts_deleted = 0;

	foreach ( array( PROFESSIONAL_POST_TYPE, SERVICE_POST_TYPE, PRICE_POST_TYPE, FAQ_POST_TYPE, INQUIRY_POST_TYPE ) as $post_type ) {
		$posts_deleted += delete_all_posts_of_type( $post_type );
	}

	delete_faq_terms();

	$options_deleted = 0;
	foreach ( array( OFFICE_PROFILE_OPTION, CONTACT_SETTINGS_OPTION, SEO_SETTINGS_OPTION, GENERATED_PAGES_OPTION ) as $option_name ) {
		if ( delete_option( $option_name ) ) {
			++$options_deleted;
		}
	}

	delete_transient( CONTACT_REACHABLE_TRANSIENT );
	delete_transient( PENDING_EMAIL_TRANSIENT );
	delete_transient( CLEANUP_LAST_RUN_TRANSIENT );

	clear_cleanup_cron();
	clear_digest_cron();

	return array(
		'posts'   => $posts_deleted,
		'options' => $options_deleted,
	);
}

/**
 * Force-deletes (bypassing Trash) every post of a given Core-owned post
 * type, and its postmeta along with it (wp_delete_post()'s normal
 * behaviour). Deliberately never touches Media Library attachments — a
 * Professional Profile's featured image reference is removed with the
 * post, but the attachment itself is untouched, exactly like WordPress's
 * own "delete post" behaviour already treats featured images.
 *
 * @param string $post_type Post type to clear.
 * @return int Number of posts deleted.
 */
function delete_all_posts_of_type( string $post_type ): int {
	$deleted = 0;

	$post_ids = get_posts(
		array(
			'post_type'      => $post_type,
			'post_status'    => 'any',
			'posts_per_page' => -1,
			'fields'         => 'ids',
			'no_found_rows'  => true,
		)
	);

	foreach ( $post_ids as $post_id ) {
		if ( wp_delete_post( $post_id, true ) ) {
			++$deleted;
		}
	}

	return $deleted;
}

/**
 * Deletes every term of the FAQ category taxonomy.
 *
 * @return void
 */
function delete_faq_terms() {
	$terms = get_terms(
		array(
			'taxonomy'   => FAQ_TAXONOMY,
			'hide_empty' => false,
			'fields'     => 'ids',
		)
	);

	if ( is_wp_error( $terms ) ) {
		return;
	}

	foreach ( $terms as $term_id ) {
		wp_delete_term( $term_id, FAQ_TAXONOMY );
	}
}
