	add_submenu_page(
		'astrea-core',
		__( 'データ削除', 'astrea-core' ),
		__( 'データ削除', 'astrea-core' ),
		'manage_options',
		PAGE_SLUG,
		__NAMESPACE__ . '\\render_page'
	);
}

