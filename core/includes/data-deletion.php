/**
 * Core — explicit, user-confirmed complete data deletion (Construction
 * Order 009, Decision 019).
 *
 * Decision 019 requires that ASTREA Core's data survive plain plugin
 * deactivation/deletion by default (see uninstall.php, which is
 * intentionally a permanent no-op), and that a full, irreversible delete
 * only ever happen through an explicit, confirmed, in-product action. The
 * Remaining Work Audit (2026-08-27) found that action had never been
 * built across any prior Construction Order — this file is it.
 *
 * Deliberately lives on its own admin page, separate from every normal
 * settings screen, so a destructive action is never one click away from a
 * benign one (per the order's "通常設定から明確に分離された領域").
 *
 * Deletion inventory (Core-owned data only — see delete_all_core_data()):
 * Office Profile option; Professional Profile / Service / Price / FAQ /
 * Inquiry posts and their postmeta; the FAQ category taxonomy's terms;
 * Contact and SEO (incl. GA4) settings options; the Setup generated-pages
 * index option; Inquiry's two Cron schedules; three known transients.
 *
 * Explicitly NOT deleted, even though ASTREA created them: ordinary
 * WordPress Pages generated by Setup (事務所概要/料金/お問い合わせ/ホーム),
 * any generated Navigation, and Media Library attachments (Professional
 * Profile photos, the OGP image). These are user content per Decision
 * 016/019 — indistinguishable from anything else the site owner made by
 * hand, and never swept up by any Core deletion path, explicit or not.
 *
 * @package Astrea\Core
 */

